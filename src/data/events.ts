import type { Bag, Stats } from "../types";
export type Outcome = { gain?: Bag; stats?: Partial<Stats>; text: string };
export type EventChoice = {
  check?: { stat: keyof Stats; min: number };
  label: string;
  cost?: Bag;
  need?: string;
  code?: string;
  hours?: number;
  chance?: number;
  success: Outcome;
  failure?: Outcome;
};
export type WildernessEvent = {
  id: string;
  zone: number;
  title: string;
  text: string;
  choices: EventChoice[];
  page?: number;
};
const choice = (
  label: string,
  text: string,
  gain: Bag = {},
  stats: Partial<Stats> = {},
  extra: Partial<EventChoice> = {},
): EventChoice => ({ label, success: { text, gain, stats }, ...extra });
const safe = (text = "保留体力，谨慎离开") =>
  choice(
    text,
    "你记下位置，选择了更稳妥的道路。",
    {},
    { spirit: 3 },
    { hours: 0.15 },
  );
const risk = (
  label: string,
  text: string,
  gain: Bag,
  fail: string,
  stats: Partial<Stats>,
  chance = 0.5,
) =>
  choice(
    label,
    text,
    gain,
    {},
    { chance, failure: { text: fail, stats }, hours: 0.5 },
  );
