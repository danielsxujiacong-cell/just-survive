export type Bag = Record<string, number>;
export type Item = {
  name: string;
  weight: number;
  kind: string;
  recipe?: Bag;
  facility?: string;
  level?: number;
  hours?: number;
  power?: number;
  range?: number;
  ammo?: string;
  heal?: Partial<Stats>;
};
export type Stats = {
  hp: number;
  hunger: number;
  water: number;
  external: number;
  internal: number;
  spirit: number;
};
export type Zone = {
  id: number;
  name: string;
  x: number;
  y: number;
  hours: number;
  resources: string[];
  enemies: string[];
  boss: string;
  story: string;
};
export type Enemy = {
  name: string;
  hp: number;
  attack: number;
  range: number;
  poison?: boolean;
};
export type Battle = {
  enemy: Enemy;
  hp: number;
  distance: number;
  turn: number;
  wolfCD: number;
  stun: number;
  bleed: number;
  message: string;
  aim: "head" | "limbs" | "torso";
  enemyStatus: Statuses;
  playerStatus: Statuses;
  environment: string;
  playerPos: number;
  enemyPos: number;
  skillCD: number;
  enemyId: string;
  origin: "region" | "journey";
};
export type State = {
  version: 3;
  time: number;
  location: number;
  selected: number;
  stats: Stats;
  bag: Bag;
  storage: Bag;
  facilities: Record<string, number>;
  fence: number;
  progress: number[];
  equipment: { melee: string; ranged: string; armor: string; tool: string };
  weather: string;
  logs: string[];
  battle: Battle | null;
  puzzle: boolean;
  board: boolean[];
  moves: number;
  puzzleDone: boolean;
  lab: boolean;
  volcano: boolean;
  eruption: number;
  blueprint: boolean;
  pearls: number[];
  wolfFound: boolean;
  wolfMeat: number;
  wolfBandage: number;
  wolf: number;
  camelFound: boolean;
  camel: boolean;
  kuru: boolean;
  friendship: number;
  canoe: boolean;
  ending: string | null;
  kills: number;
  crafted: number;
  seed: number;
  rescues: number;
  talent: string;
  journey: Journey | null;
  encounter: string | null;
  pages: number[];
  seenEvents: string[];
  seenItems: string[];
  seenEnemies: string[];
  stamps: string[];
  fishing: Fishing | null;
  defense: DefenseReport | null;
  garden: { herb: number; mint: number; ready: number };
  traps: number;
  firewall: number;
  gmUsed: number;
  turns: number;
  trackedRoute: "A" | "B" | "C" | "D";
  durability: Record<string, number>;
  loadoutReport: {
    target: number;
    weight: number;
    budget: number;
    missing: string[];
  } | null;
  sweeps: number;
  prologue: "pending" | "playing" | "done";
  milestones: { key: string; day: number; text: string }[];
  bossKills: number;
  combatFx: {
    serial: number;
    kind: "melee" | "ranged" | "wolf" | "miss";
    critical: boolean;
    weak: boolean;
    damage: number;
  } | null;
};
export type Statuses = {
  bleed: number;
  poison: number;
  root: number;
  paralyze: number;
  armorbreak: number;
  rage: number;
};
export type Journey = {
  from: number;
  to: number;
  stage: number;
  stages: number;
  hours: number;
  returning: boolean;
  incident: string | null;
  history: string[];
};
export type Fishing = {
  phase: number;
  tension: number;
  progress: number;
  attempts: number;
  last: string;
};
export type DefenseReport = {
  day: number;
  rounds: string[];
  damage: number;
  loot: number;
  barrier: number;
};
export type Archive = {
  items: string[];
  enemies: string[];
  events: string[];
  pages: number[];
  endings: string[];
};
